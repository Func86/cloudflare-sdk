/**
 * The SDK generator: a Forge plugin that writes, for each group, an `index.js` of
 * `Operation` literals with no imports and an `index.d.ts` with their types; and
 * in `_types/`, one declaration file for each prefix of the schema names.
 *
 * Only types come from Forge here, so this builds with Forge's bundler without
 * pulling its runtime in. `generator/entry.ts` is the plugin's entry module.
 */
import type { File, Forge, Group, Model, Type } from '@cloudflare/forge/plugin';
import { afterAccountOrZone } from '../../src/routes.ts';
import { namingProblems } from './names.ts';
import {
	alternativesOf,
	bodyAlternative,
	fieldNames,
	groupOf,
	holdsNull,
	type Param,
	type Report,
	type ResolvedBody,
	type ResolvedOperation,
	resolveOperation,
	takenBy,
} from './operations.ts';
import { type EnumValue, EXCLUSIVE_MODELS, type RequestVariant } from '../patches.ts';
import { jsdoc, type Mode, Models, namespaceOf, parenthesize, Printer, propertyKey } from './types.ts';

const PREAMBLE = '// Generated by generator/generate.ts. Do not edit.\n';
/** What `send` returns for server-sent events: the body, unread, for the caller to read as it arrives. */
const STREAM = 'ReadableStream<Uint8Array>';
/** Names an `export const` can't take in a module, which is strict, and are exported under an alias instead. */
const RESERVED_WORDS = new Set(
	'arguments await break case catch class const continue debugger default delete do else enum eval export extends false finally for function if implements import in instanceof interface let new null package private protected public return static super switch this throw true try typeof var void while with yield'.split(
		' ',
	),
);
/** The types a group's declarations import from the runtime, which its own names must not shadow. */
const RUNTIME_TYPES = ['AccountOrZone', 'DryRunOperation', 'ItemOf', 'Operation', 'PagedOperation', 'RootItem'] as const;

function pascalName(name: string): string {
	return name[0]!.toUpperCase() + name.slice(1);
}

/** The literal the runtime sends, without any type or documentation. */
function operationLiteral(operation: ResolvedOperation): Record<string, unknown> {
	const query = operation.params.filter((param) => param.in === 'query').map((param) => param.name);
	const headers = operation.params.filter((param) => param.in === 'header').map((param) => param.name);
	const joined = operation.joined.filter((name) => query.includes(name));
	const { body, response, page } = operation;
	const json = response.kind === 'envelope' || response.kind === 'json';
	// Several formats with no JSON are listed, so a response that names none is read as the first.
	const several = response.alternatives.length > 0;
	const responseMode = json ? (several ? 'auto' : undefined) : several ? [response.kind, ...response.alternatives] : response.kind;
	// A binary response isn't what `application/json` asks for. Text and stream alternatives
	// of JSON stay opt-in, as some are chosen by `Accept`, and a caller's headers can ask.
	const anyFormat = (!json && response.kind !== 'none') || response.alternatives.includes('bytes');
	// Nor is JSON of another media type, such as SCIM's, which a server may insist on.
	const jsonTypes = response.jsonTypes.includes('application/json') ? [] : response.jsonTypes;
	const onlyStream = response.kind === 'stream' && response.alternatives.length === 0;
	const accept = onlyStream ? 'text/event-stream' : anyFormat ? '*/*' : jsonTypes.join(', ');
	return {
		method: operation.method,
		route: operation.route,
		...(operation.accountOrZone ? { accountOrZone: true } : {}),
		...(operation.slashes.length > 0 ? { slashes: operation.slashes } : {}),
		...(query.length > 0 ? { query } : {}),
		...(joined.length > 0 ? { joined } : {}),
		...(headers.length > 0 ? { headers } : {}),
		...(body ? { body: body.kind } : {}),
		...(body?.contentType ? { contentType: body.contentType } : {}),
		...(response.kind === 'json' ? { envelope: false } : {}),
		...(responseMode ? { response: responseMode } : {}),
		...(accept ? { accept } : {}),
		...(operation.dryRun ? { dryRun: true } : {}),
		...(page ? { page } : {}),
	};
}

function operationDoc(operation: ResolvedOperation): string {
	const lines: string[] = [];
	if (operation.summary) {
		lines.push(operation.summary);
	}
	if (operation.description && operation.description !== operation.summary) {
		lines.push(...(lines.length > 0 ? [''] : []), operation.description);
	}
	if (lines.length > 0) {
		lines.push('');
	}
	const rest = operation.accountOrZone ? afterAccountOrZone(operation.route) : undefined;
	lines.push(
		rest === undefined
			? `\`${operation.method} ${operation.route}\``
			: `\`${operation.method} /accounts/{account_id}${rest}\` or \`${operation.method} /zones/{zone_id}${rest}\``,
	);
	if (operation.permissions.length > 0) {
		lines.push('', `Token permissions (any one): ${operation.permissions.join(', ')}.`);
	}
	if (operation.availability === 'beta' || operation.availability === 'alpha') {
		lines.push('', `@${operation.availability}`);
	}
	if (operation.deprecated !== undefined) {
		lines.push('', `@deprecated ${operation.deprecated}`.trimEnd());
	}
	return lines.join('\n');
}

/**
 * The key of a request field: its name, or for a name with placeholders, such as Images'
 * `meta.<field>[<operator>]`, an index signature for every name it stands for.
 */
function fieldKey(name: string, required: boolean): string {
	if (!/<[^>]+>/.test(name)) {
		return `${propertyKey(name)}${required ? '' : '?'}`;
	}
	const parts = name.split(/<[^>]+>/).map((part) => part.replace(/[\\`]|\$\{/g, (match) => `\\${match}`));
	return `[name: \`${parts.join('${string}')}\`]`;
}

function paramType(param: Param, printer: Printer): string {
	if (param.in !== 'path') {
		return printer.type(param.type, 'write', '\t');
	}
	// A path parameter is a string on the wire, whatever model names it, apart from its
	// values. A number can be given as the API sends it, or as text, which keeps an int64
	// above 2^53 or a decimal exact.
	const target = param.type?.kind === 'model' ? param.type.model.type : param.type;
	if (target?.kind === 'enum') {
		return printer.type(target, 'write', '\t');
	}
	return target?.kind === 'scalar' && target.scalar === 'number' ? 'number | string' : 'string';
}

function paramField(param: Param, type: string, required: boolean): string {
	return `${jsdoc(param.description, '\t')}\t${fieldKey(param.name, required)}: ${type};\n`;
}

/** The fields a variant that runs against the account or the zone takes, as `AccountOrZone` has them. */
const SCOPES = {
	account: '\t/** The account to run against. */\n\taccount_id: string;\n\tzone_id?: never;\n',
	zone: '\t/** The zone to run against. */\n\tzone_id: string;\n\taccount_id?: never;\n',
} as const;

/**
 * The query parameters that variants govern, as a union of the variants, in the operation's
 * order. Each takes its own parameters, limited to the values it says, and gives the group's
 * others `?: never`, as `exclusiveUnion` does for a body. A variant with a scope takes its account
 * or zone first, and one with a body takes it last.
 */
export function variantUnion(
	variants: readonly RequestVariant[],
	params: readonly Param[],
	printer: Printer,
	body?: ResolvedBody,
): string {
	const group = groupOf(variants);
	const governed = params.filter((param) => group.has(param.name));
	const model = (schemaName: string, found: Model | undefined): string => {
		if (found === undefined) {
			throw new Error(`No model is the spec's schema ${schemaName}, which a request variant names`);
		}
		return printer.type({ kind: 'model', model: found }, 'write', '\t');
	};
	const printed = variants.map((variant) => {
		const takes = takenBy(variant);
		let out = variant.scope === undefined ? '' : SCOPES[variant.scope];
		for (const param of governed.filter((param) => takes.includes(param.name))) {
			const limit = variant.values?.[param.name];
			const values = (list: readonly EnumValue[]): string => list.map((value) => JSON.stringify(value)).join(' | ');
			let type = paramType(param, printer);
			if (limit !== undefined && 'only' in limit) {
				type = values(limit.only);
			} else if (limit?.model !== undefined) {
				// The model's enum alone, with the null the parameter's own type can hold.
				const excluded = `Exclude<${model(limit.model, printer.models.named(limit.model))}, ${values(limit.not)}>`;
				type = param.type !== undefined && holdsNull(param.type) ? `${excluded} | null` : excluded;
			} else if (limit !== undefined) {
				type = `Exclude<${type}, ${values(limit.not)}>`;
			}
			out += paramField(param, type, param.required || variant.requires?.includes(param.name) === true);
		}
		for (const param of governed.filter((param) => !takes.includes(param.name))) {
			out += `\t${propertyKey(param.name)}?: never;\n`;
		}
		if (variant.body !== undefined) {
			// As a body of the operation's own can be sent as a form, where the operation also takes one.
			const form = body?.formAlternative === true ? 'FormData | ' : '';
			out += `${jsdoc(body?.description, '\t')}\tbody${body?.required === false ? '?' : ''}: ${form}${model(variant.body, bodyAlternative(body, variant.body))};\n`;
		}
		return `{\n${out}}`;
	});
	return printed.join(' | ');
}

function requestType(operation: ResolvedOperation, printer: Printer): string {
	const { variants, body } = operation;
	const group = groupOf(variants);
	let out = '';
	for (const param of operation.params.filter((param) => !group.has(param.name))) {
		out += paramField(param, paramType(param, printer), param.required);
	}
	// Each variant takes its own body, where they have one.
	if (body && !variants?.some((variant) => variant.body !== undefined)) {
		out += jsdoc(body.description, '\t');
		let type: string;
		if (body.kind === 'raw') {
			type = 'BodyInit';
		} else if (body.kind === 'form') {
			printer.form = true;
			type = `FormData | ${printer.type(body.type, 'write', '\t')}`;
			printer.form = false;
		} else {
			const json = body.exclusive && body.type ? exclusiveUnion(body.type, printer, 'write', '\t') : printer.type(body.type, 'write', '\t');
			type = `${body.formAlternative ? 'FormData | ' : ''}${json}`;
		}
		out += `\tbody${body.required ? '' : '?'}: ${type};\n`;
	}
	const parts = [
		...(takesAccountOrZone(operation) ? ['AccountOrZone'] : []),
		...(out === '' ? [] : [`{\n${out}}`]),
		...(variants === undefined ? [] : [`(${variantUnion(variants, operation.params, printer, body)})`]),
	];
	return parts.length === 0 ? '{}' : parts.join(' & ');
}

/** Whether the request type takes `AccountOrZone`, which variants that each have a scope replace. */
function takesAccountOrZone(operation: ResolvedOperation): boolean {
	return operation.accountOrZone && !operation.variants?.some((variant) => variant.scope !== undefined);
}

/**
 * A union whose value is one of its members only, as `oneOf` says. Each member says the fields
 * only the others have are absent, so a value with fields of two members is neither, and such a
 * field can be read on any member. The caller has checked that the type is such a union.
 */
export function exclusiveUnion(type: Type, printer: Printer, mode: Mode, indent: string): string {
	const { members, nullable } = alternativesOf(type)!;
	const names = members.map((member) => fieldNames(member));
	const printed = members.map((member, index) => {
		const own = names[index]!;
		const absent = [...new Set(names.flatMap((other) => [...other]))].filter((name) => !own.has(name)).sort();
		const text = parenthesize(printer.type(member, mode, indent));
		return absent.length === 0
			? text
			: `(${text} & {\n${absent.map((name) => `${indent}\t${propertyKey(name)}?: never;\n`).join('')}${indent}})`;
	});
	return [...printed, ...(nullable ? ['null'] : [])].join(' | ');
}

function resultType(operation: ResolvedOperation, printer: Printer): string {
	const { response } = operation;
	const formatType = (format: 'text' | 'bytes' | 'stream'): string =>
		format === 'text' ? 'string' : format === 'stream' ? STREAM : 'Uint8Array';
	switch (response.kind) {
		case 'none':
			return 'void';
		case 'text':
		case 'bytes':
		case 'stream':
			return [response.kind, ...response.alternatives].map(formatType).join(' | ');
		default: {
			const members = [
				...response.types.map((type) => printer.type(type, 'read')),
				...response.alternatives.map(formatType),
				...(response.noContent ? ['undefined'] : []),
			];
			return [...new Set(members)].join(' | ') || 'unknown';
		}
	}
}

function groupFiles(group: Group, operations: readonly ResolvedOperation[], models: Models): File[] {
	const directory = group.path.map((name) => name.kebab()).join('/');
	const printer = new Printer(models, undefined);
	const typesPath = `${'../'.repeat(group.path.length)}_types`;
	let script = PREAMBLE;
	let declarations = '';
	const runtime = new Set<(typeof RUNTIME_TYPES)[number]>();
	const names = new Set<string>();

	for (const operation of operations) {
		const { name } = operation;
		names.add(name);
		const local = RESERVED_WORDS.has(name) ? `${name}_` : name;
		const typeName = pascalName(name);
		const clash = RUNTIME_TYPES.find((type) => ['Request', 'Result', 'Item'].some((suffix) => `${typeName}${suffix}` === type));
		if (clash !== undefined) {
			throw new Error(`${directory}: the method ${name}'s types would shadow ${clash} from the runtime`);
		}
		const literal = JSON.stringify(operationLiteral(operation));
		script +=
			local === name
				? `export const ${name} = ${literal};\n`
				: `const ${local} = ${literal};\nexport { ${local} as ${name} };\n`;

		if (takesAccountOrZone(operation)) {
			runtime.add('AccountOrZone');
		}
		declarations += `\nexport type ${typeName}Request = ${requestType(operation, printer)};\n`;
		declarations += `export type ${typeName}Result = ${resultType(operation, printer)};\n`;
		let declared: string;
		if (operation.page && operation.dryRun) {
			throw new Error(`${directory}: ${name} pages and takes a dry run, which no type of the runtime describes`);
		}
		if (operation.page) {
			const { items } = operation.page;
			runtime.add('PagedOperation');
			runtime.add(items === undefined ? 'RootItem' : 'ItemOf');
			const item =
				items === undefined
					? `RootItem<${typeName}Result>`
					: `ItemOf<${typeName}Result, ${JSON.stringify(items)}>`;
			declarations += `export type ${typeName}Item = ${item};\n`;
			declared = `PagedOperation<${typeName}Request, ${typeName}Result, ${typeName}Item>`;
		} else {
			const kind = operation.dryRun ? 'DryRunOperation' : 'Operation';
			runtime.add(kind);
			declared = `${kind}<${typeName}Request, ${typeName}Result>`;
		}
		declarations += jsdoc(operationDoc(operation), '');
		if (local === name) {
			declarations += `export declare const ${name}: ${declared};\n`;
		} else {
			// As in index.js, only the alias is exported. The export statement keeps the
			// other declarations of this file from being exported implicitly.
			declarations += `declare const ${local}: ${declared};\nexport { ${local} as ${name} };\n`;
		}
	}

	let reexports = '';
	for (const child of group.children) {
		const namespace = child.name.camel();
		if (names.has(namespace)) {
			throw new Error(`${directory}: the method and the group ${namespace} collide`);
		}
		reexports += `export * as ${namespace} from ${JSON.stringify(`./${child.name.kebab()}/index.js`)};\n`;
	}
	script += reexports;

	let header = PREAMBLE;
	if (runtime.size > 0) {
		header += `import type { ${[...runtime].sort().join(', ')} } from "#runtime";\n`;
	}
	for (const prefix of [...printer.imports].sort()) {
		header += `import type * as ${namespaceOf(prefix)} from ${JSON.stringify(`${typesPath}/${prefix}.js`)};\n`;
	}
	return [
		{ path: `${directory}/index.js`, content: script },
		{ path: `${directory}/index.d.ts`, content: `${header}${reexports}${declarations}` },
	];
}

function modelFiles(models: Models): File[] {
	const files = new Map<string, { printer: Printer; declarations: string[] }>();
	const exclusive = new Set<string>();
	// Printing a model can queue more of them.
	for (let next = models.queue.shift(); next !== undefined; next = models.queue.shift()) {
		const { prefix, ident } = models.location(next.model, next.mode);
		let file = files.get(prefix);
		if (!file) {
			file = { printer: new Printer(models, prefix), declarations: [] };
			files.set(prefix, file);
		}
		file.printer.form = models.holdsFile(next.model);
		const doc = jsdoc(next.model.description, '');
		const { schemaName, type } = next.model;
		let printed: string;
		if (Object.hasOwn(EXCLUSIVE_MODELS, schemaName)) {
			if (alternativesOf(type)?.exclusive !== true) {
				throw new Error(`The exclusive model ${schemaName} is no longer a oneOf, so check it and remove it from EXCLUSIVE_MODELS`);
			}
			exclusive.add(schemaName);
			printed = exclusiveUnion(type, file.printer, next.mode, '');
		} else {
			printed = file.printer.type(type, next.mode);
		}
		file.declarations.push(`${doc}export type ${ident} = ${printed};\n`);
	}
	const unprinted = Object.keys(EXCLUSIVE_MODELS).filter((name) => !exclusive.has(name));
	if (unprinted.length > 0) {
		throw new Error(`These exclusive models aren't printed, so check them and remove them from EXCLUSIVE_MODELS: ${unprinted.join(', ')}`);
	}
	return [...files].map(([prefix, file]) => {
		let header = PREAMBLE;
		for (const other of [...file.printer.imports].sort()) {
			header += `import type * as ${namespaceOf(other)} from ${JSON.stringify(`./${other}.js`)};\n`;
		}
		return { path: `_types/${prefix}.d.ts`, content: `${header}\n${file.declarations.sort().join('\n')}` };
	});
}

/**
 * The groups that get files: all but Forge's root, which holds the methods without a group
 * name and has no import path. Stops if the root has any.
 */
export function namedGroups(forge: Forge): Group[] {
	const named: Group[] = [];
	for (const group of forge.groups) {
		if (group.parent !== undefined) {
			named.push(group);
		} else if (group.methods.length > 0) {
			const routes = group.methods.map((method) => `${method.httpMethod} ${method.path}`);
			throw new Error(
				`Forge put these operations in its root group, which has no import path: ${routes.join(', ')}. An operation without a name stops generation in generator/prepare.ts, or is left out through UNNAMED_OPERATIONS, so these got a method name without a group some other way, such as through an alias.`,
			);
		}
	}
	return named;
}

export function generateFiles(forge: Forge): File[] {
	const report: Report = {};
	const naming: Report = {};
	const models = new Models(forge);
	const files: File[] = [];
	const manifest: unknown[] = [];
	for (const group of namedGroups(forge)) {
		const operations = group.methods.map((method) => resolveOperation(method, report, (name) => models.named(name)));
		const groups = group.path.map((name) => name.kebab());
		group.methods.forEach((method, index) => {
			const operation = operations[index]!;
			for (const problem of namingProblems(groups, method.name.kebab(), operation)) {
				(naming[problem] ??= []).push(operation.id);
			}
		});
		files.push(...groupFiles(group, operations, models));
		for (const operation of operations) {
			manifest.push({
				id: operation.id,
				method: operation.method,
				route: operation.route,
				response: operation.response.kind,
				...(operation.response.alternatives.length > 0 ? { alternatives: operation.response.alternatives } : {}),
				...(operation.body ? { body: operation.body.kind } : {}),
				...(operation.page ? { page: operation.page } : {}),
			});
		}
	}
	files.push(...modelFiles(models));
	files.push(
		{ path: '_meta/operations.json', content: `${JSON.stringify(manifest, null, 1)}\n` },
		{ path: '_meta/report.json', content: `${JSON.stringify({ pagination: report, naming }, null, 1)}\n` },
	);
	return files;
}
